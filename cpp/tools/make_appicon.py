#!/usr/bin/env python3
"""Regenerates src/ui/appicon_data.inc (the icon compiled into the binaries, as hootedit and lestrix do) from assets/icon-*.png.
Needs Pillow; run it after changing the icon:  python3 cpp/tools/make_appicon.py"""
import pathlib, sys
from PIL import Image
root = pathlib.Path(__file__).resolve().parents[2]
out = ["// generated by tools/make_appicon.py from assets/icon-*.png (RGBA, straight alpha) - do not edit", ""]
for n in (32, 64, 128):
    im = Image.open(root / "assets" / f"icon-{n}.png").convert("RGBA")
    assert im.size == (n, n)
    data = im.tobytes()
    out.append(f"static const unsigned char kAppIcon{n}[{n * n * 4}] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append("")
(root / "cpp" / "src" / "ui" / "appicon_data.inc").write_text("\n".join(out))
print("wrote appicon_data.inc")
